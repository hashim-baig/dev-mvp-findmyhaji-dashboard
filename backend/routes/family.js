// Add family contact for a pilgrim
router.post('/pilgrims/:id/contacts', [
  body('name').notEmpty().trim(),
  body('relationship').isIn(['spouse', 'parent', 'child', 'sibling', 'other']),
  body('phone').matches(/^\+?[\d\s\-\(\)]+$/),
  body('email').optional().isEmail()
], async (req, res) => {
  try {
    const errors = validationResult(req);
    if (!errors.isEmpty()) {
      return res.status(400).json({
        error: 'Validation failed',
        details: errors.array()
      });
    }

    const { id } = req.params;
    const { name, relationship, phone, email, isPrimary = false } = req.body;

    const pilgrim = await Pilgrim.findById(id);
    if (!pilgrim) {
      return res.status(404).json({ error: 'Pilgrim not found' });
    }

    // If this is set as primary, unset other primary contacts
    if (isPrimary) {
      pilgrim.familyContacts.forEach(contact => {
        contact.isPrimary = false;
      });
    }

    pilgrim.familyContacts.push({
      name,
      relationship,
      phone,
      email,
      isPrimary
    });

    await pilgrim.save();

    res.json({
      message: 'Family contact added successfully',
      contact: pilgrim.familyContacts[pilgrim.familyContacts.length - 1]
    });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

